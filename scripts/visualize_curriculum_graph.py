VIEWS = ("courses", "topics", "coverage")


def parse_args() -> argparse.Namespace:
    here = Path(__file__).resolve().parent
    default_input = here.parent / "curriculum_graph.ttl"

    p = argparse.ArgumentParser(
        description="Visualize curriculum_graph.ttl as interactive HTML graphs.",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog=__doc__,
    )
    p.add_argument(
        "--input", "-i",
        default=str(default_input),
        metavar="FILE",
        help="Path to curriculum_graph.ttl (default: ../curriculum_graph.ttl relative to script)",
    )
    p.add_argument(
        "--view", "-v",
        choices=VIEWS + ("all",),
        default="all",
        help="Which view to render: courses / topics / coverage / all (default: all)",
    )
    p.add_argument(
        "--output-dir", "-o",
        default="out/graphs",
        metavar="DIR",
        help="Output directory for generated files (default: out/graphs)",
    )
    p.add_argument(
        "--format", "-f",
        choices=("html",),
        default="html",
        help="Output format – currently only 'html' is supported (default: html)",
    )
    p.add_argument(
        "--min-confidence",
        type=float,
        default=0.0,
        metavar="FLOAT",
        help="Minimum confidence [0.0–1.0] for course-level edges (default: 0.0 = all)",
    )
    p.add_argument(
        "--include-learning-outcomes",
        action="store_true",
        help="Show learning-outcome nodes in the coverage view",
    )
    return p.parse_args()


def main() -> None:
    args = parse_args()

    ttl_path = Path(args.input)
    if not ttl_path.exists():
        sys.exit(f"File not found: {ttl_path}")

    out_dir = Path(args.output_dir)
    out_dir.mkdir(parents=True, exist_ok=True)

    print(f"Parsing {ttl_path} …")
    g = Graph()
    g.parse(str(ttl_path), format="turtle")
    print(f"  Loaded {len(g)} triples.")

    conf_data = load_confidence(g)
    views_to_render = VIEWS if args.view == "all" else (args.view,)

    for view in views_to_render:
        if view == "courses":
            print("Building course dependency graph …")
            nxg = build_course_graph(g, conf_data, args.min_confidence)
            out_path = out_dir / "courses.html"
            render_html(
                nxg, out_path,
                "Curriculum – Course Dependency Graph"
            )

        elif view == "topics":
            print("Building topic dependency graph …")
            nxg = build_topic_graph(g)
            out_path = out_dir / "topics.html"
            render_html(
                nxg, out_path,
                "Curriculum – Topic Dependency Graph"
            )

        elif view == "coverage":
            print("Building course-topic coverage graph …")
            nxg = build_coverage_graph(g, include_lo=args.include_learning_outcomes)
            out_path = out_dir / "coverage.html"
            render_html(
                nxg, out_path,
                "Curriculum – Course–Topic Coverage",
                directed=True,
            )

    print(f"\nDone. Open any .html file in your browser.")


if __name__ == "__main__":
    main()
