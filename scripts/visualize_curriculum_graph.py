def _make_pyvis(
    nxg: nx.DiGraph,
    title: str,
    height: str = "780px",
    directed: bool = True,
) -> Network:
    net = Network(
        height=height,
        width="100%",
        directed=directed,
        bgcolor="#fafafa",
        font_color="#222",
        notebook=False,
    )
    net.heading = title
    net.set_options("""
    {
      "nodes": {
        "font": {"size": 14, "face": "Arial"},
        "borderWidth": 1,
        "shadow": true
      },
      "edges": {
        "arrows": {"to": {"enabled": true, "scaleFactor": 0.7}},
        "font": {"size": 11, "align": "middle"},
        "smooth": {"type": "dynamic"}
      },
      "physics": {
        "barnesHut": {
          "gravitationalConstant": -8000,
          "centralGravity": 0.3,
          "springLength": 180,
          "springConstant": 0.04,
          "damping": 0.09
        },
        "minVelocity": 0.75
      },
      "interaction": {
        "hover": true,
        "tooltipDelay": 200,
        "navigationButtons": true,
        "keyboard": true
      }
    }
    """)
    net.from_nx(nxg)
    return net


def _inject_legend(html_path: Path) -> None:
    """Inject the HTML legend block just before </body>."""
    content = html_path.read_text(encoding="utf-8")
    content = content.replace("</body>", LEGEND_HTML + "\n</body>", 1)
    html_path.write_text(content, encoding="utf-8")


def render_html(nxg: nx.DiGraph, out_path: Path, title: str, directed: bool = True) -> None:
    net = _make_pyvis(nxg, title, directed=directed)
    net.save_graph(str(out_path))
    _inject_legend(out_path)
    print(f"  → {out_path}")


# ─────────────────────────────────────────────────────────────────────────────
#  Main entry point
