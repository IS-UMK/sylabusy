#!/usr/bin/env python3
"""
visualize_curriculum_graph.py
─────────────────────────────
Reads an existing RDF/Turtle curriculum knowledge graph and produces
interactive HTML visualizations.

Three views are generated by default:
  A) courses   – course-level dependency graph
                 (requires / preparesFor / supports / relatedTo)
  B) topics    – topic-level concept dependency graph
                 (dependsOn / broader / narrower / skos:related / relatedTo)
  C) coverage  – bipartite course-topic coverage graph
                 (ex:covers)

Usage
─────
  python scripts/visualize_curriculum_graph.py

  # select a single view
  python scripts/visualize_curriculum_graph.py --view courses
  python scripts/visualize_curriculum_graph.py --view topics
  python scripts/visualize_curriculum_graph.py --view coverage

  # change output directory and format
  python scripts/visualize_curriculum_graph.py --output-dir out/graphs --format html

  # filter low-confidence course edges
  python scripts/visualize_curriculum_graph.py --min-confidence 0.80

  # show learning-outcome nodes in the coverage view
  python scripts/visualize_curriculum_graph.py --view coverage --include-learning-outcomes

  # use a different source file (default: curriculum_graph.ttl in repo root)
  python scripts/visualize_curriculum_graph.py --input ../curriculum_graph.ttl

Dependencies (see requirements.txt)
────────────────────────────────────
  pip install rdflib networkx pyvis
"""

