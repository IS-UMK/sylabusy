# ─────────────────────────────────────────────────────────────────────────────
#  Helpers
# ─────────────────────────────────────────────────────────────────────────────

def local_name(uri: str) -> str:
    """Return the fragment/last-path-segment of a URI."""
    if "#" in uri:
        return uri.rsplit("#", 1)[-1]
    return uri.rsplit("/", 1)[-1]


def best_label(g: Graph, uri: URIRef, prefer_lang: str = "en") -> str:
    """
    Return the cleanest available label for *uri*:
      1. skos:prefLabel in *prefer_lang*
      2. skos:prefLabel in any language
      3. rdfs:label in *prefer_lang*
      4. rdfs:label in any language
      5. URI local name
    """
    for prop in (SKOS.prefLabel, RDFS.label):
        candidates = list(g.objects(uri, prop))
        # prefer the requested language
        for c in candidates:
            if getattr(c, "language", None) == prefer_lang:
                return str(c)
        # any language
        if candidates:
            return str(candidates[0])
    return local_name(str(uri))


def load_confidence(g: Graph) -> dict:
    """
    Return a dict  (subject, predicate, object) -> float
    collected from all reified rdf:Statement nodes that carry ex:confidence.
    """
    conf: dict = {}
    for st in g.subjects(RDF.type, RDF.Statement):
        s = g.value(st, RDF.subject)
        p = g.value(st, RDF.predicate)
        o = g.value(st, RDF.object)
        c = g.value(st, EX.confidence)
        note = g.value(st, EX.evidenceNote)
        if s and p and o:
            key = (str(s), str(p), str(o))
            conf[key] = {
                "confidence": float(str(c)) if c else None,
                "note": str(note) if note else "",
            }
    return conf


def edge_tooltip(label: str, confidence: Optional[float], note: str) -> str:
    parts = [f"<b>{label}</b>"]
    if confidence is not None:
        parts.append(f"confidence: {confidence:.2f}")
    if note:
        parts.append(f"<i>{note}</i>")
    return "<br>".join(parts)


# ─────────────────────────────────────────────────────────────────────────────
#  Core: build NetworkX graphs from RDF
# ─────────────────────────────────────────────────────────────────────────────

def build_course_graph(
    g: Graph,
    conf_data: dict,
    min_confidence: float = 0.0,
) -> nx.DiGraph:
    """Build a directed graph of course-level edges."""
    nxg = nx.DiGraph()

    # collect courses
    for course in g.subjects(RDF.type, EX.Course):
        label = best_label(g, course)
        alt = g.value(course, SKOS.altLabel)
        alt_str = f" ({alt})" if alt else ""
        sem = g.value(course, EX.offeredInSemester)
        sem_label = best_label(g, sem) if sem else ""
        nxg.add_node(
            str(course),
            label=label + alt_str,
            title=f"<b>{label}</b><br>Semester: {sem_label}<br><i>{local_name(str(course))}</i>",
            color=COLORS["course"],
            size=30,
            shape="dot",
            node_type="course",
        )

    # collect edges
    course_relations = [
        EX.requires, EX.preparesFor, EX.supports, EX.relatedTo
    ]
    for pred in course_relations:
        style = EDGE_STYLE.get(str(pred), ("#666666", False, local_name(str(pred))))
        color, dashes, elabel = style
        for s, o in g.subject_objects(pred):
            if str(s) not in nxg or str(o) not in nxg:
                continue
            key = (str(s), str(pred), str(o))
            cd = conf_data.get(key, {})
            c_val = cd.get("confidence")
            if c_val is not None and c_val < min_confidence:
                continue
            note = cd.get("note", "")
            tip = edge_tooltip(elabel, c_val, note)
            nxg.add_edge(
                str(s), str(o),
                label=elabel,
                title=tip,
                color=color,
                dashes=dashes,
                width=3 if not dashes else 2,
                pred=str(pred),
            )
    return nxg


def build_topic_graph(g: Graph) -> nx.DiGraph:
    """Build a directed graph of topic-level edges."""
    nxg = nx.DiGraph()

    for topic in g.subjects(RDF.type, EX.Topic):
        label = best_label(g, topic)
        nxg.add_node(
            str(topic),
            label=label,
            title=f"<b>{label}</b><br><i>{local_name(str(topic))}</i>",
            color=COLORS["topic"],
            size=22,
            shape="dot",
            node_type="topic",
        )

    topic_relations = [
        (EX.dependsOn,    False),
        (EX.relatedTo,    True),
        (SKOS.broader,    True),
        (SKOS.narrower,   True),
        (SKOS.related,    True),
    ]
    for pred, default_dash in topic_relations:
        style = EDGE_STYLE.get(str(pred), ("#888888", default_dash, local_name(str(pred))))
        color, dashes, elabel = style
        for s, o in g.subject_objects(pred):
            if str(s) not in nxg or str(o) not in nxg:
                continue
            nxg.add_edge(
                str(s), str(o),
                label=elabel,
                title=f"<b>{elabel}</b>",
                color=color,
                dashes=dashes,
                width=2 if not dashes else 1,
                pred=str(pred),
            )
    return nxg


def build_coverage_graph(
    g: Graph,
    include_lo: bool = False,
) -> nx.Graph:
    """Build a bipartite course–topic coverage graph (undirected for layout)."""
    nxg = nx.DiGraph()

    for course in g.subjects(RDF.type, EX.Course):
        label = best_label(g, course)
        alt = g.value(course, SKOS.altLabel)
        alt_str = f" ({alt})" if alt else ""
        sem = g.value(course, EX.offeredInSemester)
        sem_label = best_label(g, sem) if sem else ""
        nxg.add_node(
            str(course),
            label=label + alt_str,
            title=f"<b>{label}</b><br>Semester: {sem_label}",
            color=COLORS["course"],
            size=34,
            shape="dot",
            group="course",
        )

    for topic in g.subjects(RDF.type, EX.Topic):
        label = best_label(g, topic)
        nxg.add_node(
            str(topic),
            label=label,
            title=f"<b>{label}</b><br><i>{local_name(str(topic))}</i>",
            color=COLORS["topic"],
            size=18,
            shape="dot",
            group="topic",
        )

    if include_lo:
        for lo in g.subjects(RDF.type, EX.LearningOutcome):
            label = best_label(g, lo, prefer_lang="pl")
            nxg.add_node(
                str(lo),
                label=label[:60] + ("…" if len(label) > 60 else ""),
                title=f"<b>Learning Outcome</b><br>{label}",
                color=COLORS["lo"],
                size=14,
                shape="diamond",
                group="lo",
            )

    # covers edges
    style = EDGE_STYLE[str(EX.covers)]
    color, dashes, elabel = style
    for s, o in g.subject_objects(EX.covers):
        if str(s) in nxg and str(o) in nxg:
            nxg.add_edge(
                str(s), str(o),
                label="covers",
                title="<b>covers</b>",
                color=color,
                dashes=False,
                width=1,
            )

    if include_lo:
        # hasLearningOutcome edges
        for s, o in g.subject_objects(EX.hasLearningOutcome):
            if str(s) in nxg and str(o) in nxg:
                nxg.add_edge(str(s), str(o),
                             label="hasOutcome",
                             title="<b>hasLearningOutcome</b>",
                             color="#999999", dashes=True, width=1)
        # mapsTo edges
        for s, o in g.subject_objects(EX.mapsTo):
            if str(s) in nxg and str(o) in nxg:
                nxg.add_edge(str(s), str(o),
                             label="mapsTo",
                             title="<b>mapsTo</b>",
                             color="#BBBBBB", dashes=True, width=1)

    return nxg


